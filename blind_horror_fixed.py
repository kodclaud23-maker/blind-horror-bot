async def cmd_start(update: Update, context: ContextTypes.DEFAULT_TYPE):
    user = update.effective_user
    is_admin = (user.id == ADMIN_ID)

    if is_admin:
        keyboard = [
            [InlineKeyboardButton("📤 Опубликовать следующий пост", callback_data="pub_next")],
            [InlineKeyboardButton("🔀 Случайный пост",              callback_data="pub_random")],
            [InlineKeyboardButton("📋 Список всех тем",             callback_data="list_posts")],
            [InlineKeyboardButton("⏰ Расписание",                   callback_data="show_schedule")],
            [InlineKeyboardButton("📊 Статистика",                   callback_data="show_stats")],
        ]
        await update.message.reply_text(
            "👋 Привет, Admin!\n\n"
            f"Бот *Blind Horror* запущен.\n"
            f"Готовых постов: {len(POSTS)}\n"
            f"Расписание: {', '.join(SCHEDULE_TIMES)} МСК\n\n"
            "Выбери действие:",
            reply_markup=InlineKeyboardMarkup(keyboard),
            parse_mode="Markdown"
        )
    else:
        await update.message.reply_text(
            f"👁 Привет, {user.first_name}.\n\n"
            "Это канал *Blind Horror* — о тёмной стороне психологии.\n\n"
            f"Подпишись: {CHANNEL_ID}",
            parse_mode="Markdown"
        )


async def cmd_preview(update: Update, context: ContextTypes.DEFAULT_TYPE):
    """Предпросмотр следующего поста. /preview"""
    if update.effective_user.id != ADMIN_ID:
        return
    post = POSTS[post_index % len(POSTS)]
    keyboard = [
        [InlineKeyboardButton("📤 Опубликовать этот", callback_data="pub_next")],
        [InlineKeyboardButton("⏭ Пропустить",         callback_data="skip_post")],
    ]
    await update.message.reply_text(
        f"👁 *Предпросмотр поста #{post_index + 1}:*\n\n{post}",
        reply_markup=InlineKeyboardMarkup(keyboard),
        parse_mode="Markdown"
    )


async def cmd_stats(update: Update, context: ContextTypes.DEFAULT_TYPE):
    """Статистика. /stats"""
