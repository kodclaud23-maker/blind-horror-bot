def auto_post_job():
    global post_index
    if app_instance is None:
        return

    post = POSTS[post_index % len(POSTS)]
    post_index += 1

    try:
        import asyncio
        loop = asyncio.new_event_loop()
        asyncio.set_event_loop(loop)
        loop.run_until_complete(
            app_instance.bot.send_message(chat_id=CHANNEL_ID, text=post)
        )
        loop.close()
        logging.info(f"✅ Автопост #{post_index} опубликован")
    except Exception as e:
        logging.error(f"❌ Ошибка: {e}")


def run_scheduler():
    for t in SCHEDULE_TIMES:
        schedule.every().day.at(t).do(auto_post_job)
    logging.info(f"⏰ Расписание: {', '.join(SCHEDULE_TIMES)} МСК")
    while True:
        schedule.run_pending()
        time.sleep(30)

