async def button_handler(update: Update, context: ContextTypes.DEFAULT_TYPE):
    global post_index
    query = update.callback_query
    await query.answer()
    data = query.data

    if data == "pub_next":
        post = POSTS[post_index % len(POSTS)]
        await context.bot.send_message(chat_id=CHANNEL_ID, text=post)
        post_index += 1
        await query.message.reply_text(
            f"✅ Пост #{post_index} опубликован!\n"
            f"Следующий: #{post_index % len(POSTS) + 1} из {len(POSTS)}"
        )

    elif data == "pub_random":
        post = random.choice(POSTS)
        await context.bot.send_message(chat_id=CHANNEL_ID, text=post)
        await query.message.reply_text("✅ Случайный пост опубликован!")

    elif data == "skip_post":
        post_index += 1
        await query.message.reply_text(f"⏭ Пропущено. Следующий: #{post_index % len(POSTS) + 1}")

    elif data == "list_posts":
        lines = []
        for i, p in enumerate(POSTS):
            first_line = p.split("\n")[0][:50]
            lines.append(f"{i+1}. {first_line}")
        text = "\n".join(lines)
        await query.message.reply_text(f"📋 *Все посты:*\n\n{text}", parse_mode="Markdown")

    elif data == "show_schedule":
        await query.message.reply_text(
            "⏰ *Расписание автопостинга:*\n" +
            "\n".join([f"• {t} МСК" for t in SCHEDULE_TIMES]) +
            f"\n\nКанал: {CHANNEL_ID}",
            parse_mode="Markdown"
        )

    elif data == "show_stats":
        await query.message.reply_text(
            f"📊 Всего постов: {len(POSTS)}\n"
            f"Опубликовано: {post_index}\n"
            f"Следующий: #{post_index % len(POSTS) + 1}"
        )

