def auto_post():
    global post_index
    post = POSTS[post_index % len(POSTS)]
    result = send_message(CHANNEL_ID, post)
    if result and result.get("ok"):
        post_index += 1
        logging.info(f"✅ Автопост #{post_index} опубликован")
    else:
        logging.error(f"❌ Ошибка автопоста: {result}")


def run_scheduler():
    for t in SCHEDULE_TIMES:
        schedule.every().day.at(t).do(auto_post)
    logging.info(f"⏰ Расписание: {', '.join(SCHEDULE_TIMES)} UTC")
    while True:
        schedule.run_pending()
        time.sleep(30)

# ══════════════════════════════════════
#   ОСНОВНОЙ ЦИКЛ
# ══════════════════════════════════════

def main():
    logging.info("🚀 Запуск Blind Horror Bot...")

    # Запускаем планировщик
    threading.Thread(target=run_scheduler, daemon=True).start()

    offset = None
    logging.info("✅ Бот работает!")

    while True:
        updates = get_updates(offset)

        for update in updates:
            offset = update["update_id"] + 1

            # Обработка callback кнопок
            if "callback_query" in update:
                handle_callback(update["callback_query"])
                continue

            # Обработка сообщений
            if "message" not in update:
                continue

            message = update["message"]
            chat_id = message["chat"]["id"]
            user = message.get("from", {})
            text = message.get("text", "")

            if text == "/start":
                handle_start(chat_id, user)
            elif text.startswith("/"):
                handle_start(chat_id, user)
            else:
                handle_message(chat_id, text, user)

        time.sleep(1)


if __name__ == "__main__":
    main()
