def handle_callback(callback_query):
    global post_index
    chat_id = callback_query["from"]["id"]
    data = callback_query.get("data", "")

    if chat_id != ADMIN_ID:
        return

    if data == "pub_next":
        post = POSTS[post_index % len(POSTS)]
        result = send_message(CHANNEL_ID, post)
        if result and result.get("ok"):
            post_index += 1
            send_message(chat_id, f"✅ Пост #{post_index} опубликован в канале!")
        else:
            send_message(chat_id, f"❌ Ошибка публикации. Проверь что бот добавлен в канал как администратор.")

    elif data == "pub_random":
        post = random.choice(POSTS)
        result = send_message(CHANNEL_ID, post)
        if result and result.get("ok"):
            send_message(chat_id, "✅ Случайный пост опубликован!")
        else:
            send_message(chat_id, "❌ Ошибка. Бот должен быть администратором канала.")

    elif data == "show_stats":
        send_message(chat_id,
            f"📊 *Статистика*\n\n"
            f"Всего постов: {len(POSTS)}\n"
            f"Опубликовано: {post_index}\n"
            f"Следующий: #{post_index % len(POSTS) + 1}\n"
            f"Канал: {CHANNEL_ID}"
        )

    # Ответить на callback
    try:
        requests.post(f"{API}/answerCallbackQuery",
            json={"callback_query_id": callback_query["id"]}, timeout=5)
    except:
        pass


def handle_message(chat_id, text, user):
    is_admin = (chat_id == ADMIN_ID)

    if is_admin:
        handle_start(chat_id, user)
        return

    # Пересылаем сообщение админу
    name = user.get("username") or user.get("first_name", "")
    try:
        send_message(ADMIN_ID, f"💬 @{name} написал:\n\n«{text}»")
    except:
        pass

    replies = [
        "Интересный вопрос! Раскроем эту тему в ближайших постах 🔥",
        f"Спасибо! Подпишись на канал — там много полезного 👁\n{CHANNEL_ID}",
        "Хороший вопрос. Следи за каналом — скоро будет пост именно на эту тему!",
        "Загляни в канал — там найдёшь ответ 📌",
    ]
    send_message(chat_id, random.choice(replies))

